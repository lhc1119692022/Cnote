const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'cnote-dialog-test-')))
app.disableHardwareAcceleration()
const delay = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds))
const timeout = setTimeout(() => { console.error('Dialog regression timed out'); app.exit(1) }, 60000)

app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1440, height: 1100, webPreferences: { offscreen: true, contextIsolation: true, sandbox: true } })
  const evaluate = async source => { try { return await window.webContents.executeJavaScript(source, true) } catch (error) { throw new Error(source + "\n" + error.message) } }
  const clickText = text => evaluate(
    '(() => { const button = Array.from(document.querySelectorAll("button")).find(button => button.textContent.trim() === ' + JSON.stringify(text) + '); if (!button) throw Error("Button missing: " + ' + JSON.stringify(text) + '); button.click(); })()'
  )
  const type = async (selector, text) => {
    const point = await evaluate('(() => { const input = document.querySelector(' + JSON.stringify(selector) + '); if (!input) throw Error("Input missing"); const box = input.getBoundingClientRect(); return { x: Math.round(box.x + 10), y: Math.round(box.y + box.height / 2) }; })()')
    window.webContents.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseUp', ...point, button: 'left', clickCount: 1 })
    await delay(75)
    assert.equal(await evaluate('document.activeElement === document.querySelector(' + JSON.stringify(selector) + ')'), true, selector + ' should receive mouse focus')
    await window.webContents.insertText(text)
    await delay(50)
    assert.equal(await evaluate('document.querySelector(' + JSON.stringify(selector) + ').value'), text)
  }
  try {
    await window.loadFile(path.resolve(__dirname, '../../web/dist/index.html'))
    for (let attempt = 0; attempt < 100; attempt++) {
      if (await evaluate('document.body.innerText.includes("创建 Flow")')) break
      await delay(50)
    }
    await evaluate('window.alert = window.confirm = () => { throw Error("Native dialog used") }; true')
    for (let cycle = 0; cycle < 4; cycle++) {
      await clickText('创建 Flow')
      await delay(50)
      assert.equal(await evaluate('document.activeElement.placeholder'), '输入 Flow 名称')
      assert.equal(await evaluate('document.querySelector("[role=dialog]").getBoundingClientRect().width'), 448, 'Flow dialog retains its original width')
      await type('input[placeholder="输入 Flow 名称"]', '首开输入' + cycle)
      await type('input[placeholder="输入描述..."]', '描述输入')
      await clickText('取消')
      await delay(30)
      assert.equal(await evaluate('document.querySelectorAll("[role=dialog]").length'), 0)
    }
    await clickText('创建 Flow')
    await delay(50)
    const drag = await evaluate('(() => { const box = document.querySelector("[role=dialog] input").getBoundingClientRect(); return {x: Math.round(box.x + 10), y: Math.round(box.y + 10)} })()')
    window.webContents.sendInputEvent({ type: 'mouseDown', ...drag, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseMove', x: 5, y: 5 })
    window.webContents.sendInputEvent({ type: 'mouseUp', x: 5, y: 5, button: 'left', clickCount: 1 })
    await delay(50)
    assert.equal(await evaluate('document.querySelectorAll("[role=dialog]").length'), 1, 'dragging out must not close dialog')
    window.webContents.sendInputEvent({ type: 'mouseDown', x: 5, y: 5, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseUp', x: 5, y: 5, button: 'left', clickCount: 1 })
    await delay(50)
    assert.equal(await evaluate('document.querySelectorAll("[role=dialog]").length'), 0, 'backdrop click closes dialog')
    await evaluate('document.querySelector("main aside button").click()')
    await delay(50)
    await type('input[placeholder="输入文件夹名称"]', '回归测试文件夹')
    await clickText('创建')
    await delay(75)
    await evaluate(`document.querySelector('[aria-label="删除文件夹 回归测试文件夹"]').click()`)
    await delay(50)
    await clickText('取消')
    await delay(50)
    assert(await evaluate(`Boolean(document.querySelector('[aria-label="删除文件夹 回归测试文件夹"]'))`))
    await evaluate(`document.querySelector('[aria-label="删除文件夹 回归测试文件夹"]').click()`)
    await delay(50)
    await clickText('确定')
    await delay(50)
    assert.equal(await evaluate(`Boolean(document.querySelector('[aria-label="删除文件夹 回归测试文件夹"]'))`), false)
    await clickText('创建 Flow')
    await delay(50)
    await type('input[placeholder="输入 Flow 名称"]', '确认后输入')
    await clickText('取消')
    await evaluate('location.hash = "#/sources"; true')
    await delay(300)
    await clickText('新建内容')
    await delay(50)
    await type('input[placeholder="输入内容标题"]', '新内容输入')
    await clickText('取消')
    await evaluate('location.hash = "#/settings/api-keys"; true')
    await delay(400)
    await clickText('新增渠道')
    await delay(50)
    assert.equal(await evaluate('document.querySelector("[role=dialog]").getBoundingClientRect().width'), 560, 'custom channel width is preserved')
    await type('input[placeholder="输入 API Key"]', 'test-only-not-a-real-key')
    await clickText('取消')
    console.log('Electron dialog input: first open, repeated open, switching fields, drag release, backdrop click, folder deletion cancel/accept, post-confirm input, source and channel dialogs: PASS')
    clearTimeout(timeout)
    window.destroy()
    app.exit(0)
  } catch (error) {
    console.error(error)
    clearTimeout(timeout)
    window.destroy()
    app.exit(1)
  }
})
