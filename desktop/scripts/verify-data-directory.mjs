import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { migrateDataDirectory, directoryUsage, assertMigrationPaths } = require('../dist/runtime/data-directory.js')
const { NativeStoragePort } = require('../dist/runtime/storage-port.js')
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cnote-data-test-'))
const source = path.join(root, 'source')
const target = path.join(root, 'target')
fs.mkdirSync(path.join(source, 'Cnote', 'storage'), { recursive: true })
fs.mkdirSync(path.join(source, 'Cache'))
fs.mkdirSync(path.join(source, 'Partitions', 'browser'), { recursive: true })
fs.writeFileSync(path.join(source, 'Cache', 'cache-file'), 'discardable')
fs.writeFileSync(path.join(source, 'Partitions', 'browser', 'Cookies'), 'cookie-fixture')
fs.writeFileSync(path.join(source, 'secrets.json'), 'fixture-not-a-real-secret')
const store = new NativeStoragePort(path.join(source, 'Cnote', 'storage'))
await store.write('doc:flow:fixture', new TextEncoder().encode('fixture-document'))
await store.write('resource:sha256-test', new Uint8Array([1, 2, 3]))
assert.deepEqual((await store.keys()).sort(), ['doc:flow:fixture', 'resource:sha256-test'])
assert.throws(() => assertMigrationPaths(source, path.join(source, 'nested')), /包含/)
assert.throws(() => assertMigrationPaths(source, root), /包含/)
const occupied = path.join(root, 'occupied')
fs.mkdirSync(occupied)
fs.writeFileSync(path.join(occupied, 'keep'), 'preserve')
assert.throws(() => migrateDataDirectory(source, occupied), /空文件夹/)
assert.equal(fs.readFileSync(path.join(occupied, 'keep'), 'utf8'), 'preserve')
migrateDataDirectory(source, target)
assert.ok(fs.existsSync(path.join(source, 'secrets.json')), 'original survives migration')
assert.equal(fs.readFileSync(path.join(target, 'secrets.json'), 'utf8'), 'fixture-not-a-real-secret')
assert.equal(fs.readFileSync(path.join(target, 'Partitions', 'browser', 'Cookies'), 'utf8'), 'cookie-fixture')
assert.equal(fs.existsSync(path.join(target, 'Cache')), false)
const migrated = new NativeStoragePort(path.join(target, 'Cnote', 'storage'))
assert.deepEqual(await migrated.read('resource:sha256-test'), new Uint8Array([1, 2, 3]))
assert.equal(directoryUsage(source).resources, 3)
assert.ok(directoryUsage(source).cache > 0)
assert.equal(directoryUsage(target).cache, 0)
assert.throws(() => migrateDataDirectory(path.join(root, 'absent'), path.join(root, 'next')), /不可用/)
const { Script } = await import('node:vm')
const locationCode = fs.readFileSync(new URL('../dist/runtime/storage-location.js', import.meta.url), 'utf8')
const mockPaths = { userData: path.join(root, 'profile'), appData: path.join(root, 'settings'), sessionData: path.join(root, 'profile') }
fs.mkdirSync(mockPaths.userData)
const mockApp = { getPath: name => mockPaths[name], setPath: (name, value) => { mockPaths[name] = value }, setAppLogsPath: value => { mockPaths.logs = value } }
const loadLocation = () => {
  const module = { exports: {} }
  new Script('(function(require,module,exports,process){' + locationCode + '\n})').runInThisContext()(name => name === 'electron' ? { app: mockApp } : name === './data-directory' ? require('../dist/runtime/data-directory.js') : require(name), module, module.exports, { env: {} })
  return module.exports
}
let location = loadLocation()
location.configureStorageLocation()
fs.writeFileSync(path.join(mockPaths.userData, 'document.fixture'), 'profile-content')
const newLocation = path.join(root, 'moved-profile')
location.setStorageLocation(newLocation)
assert.equal(location.getStorageLocationInfo().restartRequired, true)
assert.equal(mockPaths.userData, path.join(root, 'profile'), 'migration is deferred until restart')
location = loadLocation()
location.configureStorageLocation()
assert.equal(mockPaths.userData, newLocation)
assert.equal(mockPaths.sessionData, newLocation)
assert.equal(fs.readFileSync(path.join(newLocation, 'document.fixture'), 'utf8'), 'profile-content')
assert.ok(fs.existsSync(path.join(root, 'profile', 'document.fixture')))
assert.equal(location.getStorageLocationInfo().restartRequired, false)
const configured = path.join(mockPaths.appData, 'Cnote', 'storage-location.json')
fs.writeFileSync(configured, JSON.stringify({ sessionDataPath: path.join(root, 'missing-drive') }))
assert.throws(() => loadLocation().configureStorageLocation(), /不存在/)
assert.equal(mockPaths.userData, newLocation, 'unavailable directory never silently falls back')
console.log('Data directory PASS: copy/hash validation, nested/nonempty/missing-source guards, original preservation, cookies/cache classification, deferred restart migration and no fallback. Fixtures: ' + root)
