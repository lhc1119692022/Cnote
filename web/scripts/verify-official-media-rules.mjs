import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import vm from 'node:vm'
import ts from 'typescript'

const source = readFileSync(new URL('../src/lib/generation/official-media-rules.ts', import.meta.url), 'utf8')
const context = vm.createContext({ exports: {}, TextEncoder, console })
vm.runInContext(ts.transpile(source, { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }), context)
const { officialMediaProfile, validateMediaFile, validateMediaCollection, withOfficialMediaCapabilities, officialRequestLimitError } = context.exports
const reference = (type = 'image', id = 'sample', role = 'reference_image') => ({ id, type, role, source: 'local', order: 0, fileName: `${id}.png` })
const image = { bytes: 20_000_000, format: 'png', width: 1024, height: 1024 }
const video = { bytes: 30_000_000, format: 'mp4', width: 1280, height: 720, fps: 24, duration: 5, videoCodec: 'h264', hasAudio: true, audioCodec: 'aac' }
const wan = officialMediaProfile('wan-3.0-1080p')
const sd20 = officialMediaProfile('doubao-seedance-2.0')
const sd25 = officialMediaProfile('S-2.5-301010-内置过脸')
const h3 = officialMediaProfile('MiniMax-H3-量化版')
assert.equal(wan.id, 'wan-3')
assert.equal(officialMediaProfile('provider/wan-3.0-custom').id, 'wan-3')
assert.equal(sd20.id, 'seedance-2.0')
assert.equal(sd25.id, 'seedance-2.5')
assert.equal(h3.id, 'minimax-h3')
for (const id of ['S-满血2.0-稳定-线路一', 'S-2.0fast满血933-卡脸', 'seedance-2-fast', 'sd-2.0']) assert.equal(officialMediaProfile(id)?.id, 'seedance-2.0')
for (const id of ['wan-30', 'wan-2.2', 'seedance-20', 'custom-model', 'minimax-h30']) assert.equal(officialMediaProfile(id), undefined)
assert.equal(validateMediaFile(wan, reference(), image).status, 'valid')
assert.equal(validateMediaFile(wan, reference(), { ...image, bytes: 20_000_001 }).violations[0].code, 'bytes')
assert.equal(validateMediaFile(sd20, reference(), { ...image, bytes: 30_000_000 }).status, 'invalid')
assert.equal(validateMediaFile(sd20, reference(), { ...image, bytes: 29_999_999 }).status, 'valid')
assert.equal(validateMediaFile(h3, reference(), { ...image, bytes: 30_000_000 }).status, 'valid')
assert.equal(validateMediaFile(h3, reference(), { ...image, width: 5760, height: 256 }).status, 'valid')
assert.equal(validateMediaFile(h3, reference('image', 'first', 'first_frame'), { ...image, width: 5760, height: 256 }).violations[0].code, 'ratio')
assert.equal(validateMediaFile(wan, reference(), { ...image, width: 240, height: 1920 }).status, 'valid')
assert.equal(validateMediaFile(wan, reference(), { ...image, width: 240, height: 1921 }).violations[0].code, 'ratio')
assert.equal(validateMediaFile(sd20, reference('video'), video).status, 'valid')
assert.equal(validateMediaFile(sd20, reference('video'), { ...video, width: 3326, height: 2494 }).status, 'valid')
assert.equal(validateMediaFile(sd20, reference('video'), { ...video, width: 3327, height: 2494 }).violations[0].code, 'pixels')
assert.equal(validateMediaFile(sd20, reference('video'), { ...video, width: 300, height: 300 }).violations[0].code, 'pixels')
assert.equal(validateMediaFile(sd20, reference('video'), { ...video, fps: 23.99 }).violations[0].code, 'fps')
assert.equal(validateMediaFile(sd20, reference('video'), { ...video, fps: undefined }).status, 'unverifiable')
assert.equal(validateMediaFile(sd20, reference('video'), { ...video, videoCodec: 'av1' }).violations[0].code, 'codec')
assert.equal(validateMediaFile(sd20, reference('video'), { ...video, format: 'mov', audioCodec: 'pcm' }).status, 'valid')
assert.equal(validateMediaFile(sd20, reference('video'), { ...video, audioCodec: 'pcm' }).status, 'invalid')
assert.equal(validateMediaFile(h3, reference('video'), { ...video, format: 'mov', audioCodec: 'pcm' }).status, 'invalid')
assert.equal(validateMediaFile(sd25, reference('video'), { ...video, duration: 3 }, 'video-edit').status, 'invalid')
assert.equal(validateMediaFile(sd25, reference('video'), { ...video, duration: 3 }, 'reference-to-video').status, 'valid')
assert.equal(validateMediaFile(wan, reference('audio'), { bytes: 15_000_000, format: 'wav', duration: 1 }).status, 'valid')
assert.equal(validateMediaFile(sd20, reference('audio'), { bytes: 15_000_000, format: 'wav', duration: 1 }).status, 'invalid')
for (const value of [undefined, NaN, Infinity, 0, -1]) assert.equal(validateMediaFile(wan, reference(), { ...image, width: value }).status, 'unverifiable')
const references = [reference('video', 'one'), reference('video', 'two')]
assert.equal(validateMediaCollection(wan, references, new Map([['one', { ...video, duration: 10 }], ['two', { ...video, duration: 6 }]]))[0].code, 'total-duration')
assert.equal(validateMediaCollection(sd20, Array.from({ length: 4 }, (_, index) => reference('audio', `audio-${index}`)), new Map())[0].code, 'count')
const mixed = [...Array.from({ length: 9 }, (_, index) => reference('image', `image-${index}`)), ...Array.from({ length: 3 }, (_, index) => reference('video', `video-${index}`)), reference('audio', 'voice')]
assert.equal(validateMediaCollection(h3, mixed, new Map())[0].code, 'total-count')
const channelModel = { id: 'minimax_h3', name: 'H3', capabilities: ['image-to-video'], inputTypes: ['image'], maxImages: 1, maxVideos: 0, maxAudios: 0 }
const official = withOfficialMediaCapabilities(channelModel)
assert.equal(official.maxImages, 9)
assert.equal(official.maxVideos, 3)
assert.equal(official.maxAudios, 3)
assert.equal(official.inputTypes.join(','), 'image,video,audio')
assert.equal(channelModel.maxImages, 1)
assert.equal(withOfficialMediaCapabilities({ ...channelModel, id: 'wan-3' }).maxImages, undefined)
assert.equal(officialRequestLimitError(h3, { prompt: '人'.repeat(7001) }).includes('7000'), true)
assert.equal(officialRequestLimitError(h3, { prompt: '😀'.repeat(7000) }), undefined)
assert.equal(officialRequestLimitError(h3, { prompt: '' }, 'x'.repeat(64_000_001)).includes('64 MB'), true)
console.log('Official media rules: byte boundaries, roles, versions, codecs, collections, aliases and channel independence passed.')
